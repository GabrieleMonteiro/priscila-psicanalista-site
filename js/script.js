// =========================================
// INICIALIZAÇÃO DO SITE
// =========================================

document.addEventListener("DOMContentLoaded", () => {

  // =========================================
  // IDIOMA
  // =========================================

  const languageToggle = document.querySelector("#language-toggle");

  let currentLanguage = localStorage.getItem("site-language") || "pt";

  if (!["pt", "en"].includes(currentLanguage)) {
    currentLanguage = "pt";
  }

  // Guarda o conteúdo original de cada nó de texto.
  const originalTextNodes = new Map();

  const textWalker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const parent = node.parentElement;

        if (!parent) return NodeFilter.FILTER_REJECT;

        if (parent.closest("script, style, noscript")) {
          return NodeFilter.FILTER_REJECT;
        }

        if (!node.textContent.trim()) {
          return NodeFilter.FILTER_REJECT;
        }

        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let textNode;

  while ((textNode = textWalker.nextNode())) {
    originalTextNodes.set(textNode, textNode.textContent);
  }

  // Traduções de atributos de acessibilidade.
  const attributeTranslations = {
    "aria-label": {
      "Priscila, página inicial": "Priscila, home page",
      "Espaço para a logo da Priscila": "Space for Priscila's logo",
      "Navegação principal": "Main navigation",
      "Abrir menu": "Open menu",
      "Fechar menu": "Close menu",
      "Navegar pelas seções": "Navigate through sections",
      "Role para conhecer a Priscila": "Scroll to discover Priscila",
      "Escolher apresentação": "Choose a presentation",
      "Slide 1": "Slide 1",
      "Slide 2": "Slide 2",
      "Slide 3": "Slide 3",
      "Slide anterior": "Previous slide",
      "Próximo slide": "Next slide",
      "Fale com Priscila pelo WhatsApp": "Contact Priscila via WhatsApp",
      "Change language": "Change language",
      "Ativar modo escuro": "Enable dark mode",
      "Ativar modo claro": "Enable light mode"
    },

    "alt": {
      "Logo de Priscila": "Priscila's logo",
      "Ambiente tranquilo e acolhedor com luz natural": "A peaceful and welcoming space with natural light",
      "Priscila, psicanalista": "Priscila, psychoanalyst",
      "Sala de atendimento com decoração natural e aconchegante": "A cozy consultation room with natural decor",
      "Luz suave atravessando uma paisagem natural": "Soft light shining through a natural landscape",
      "Paisagem serena com montanhas e natureza": "A peaceful landscape with mountains and nature"
    }
  };

  // Guarda os atributos originais.
  const originalAttributes = new Map();

  document.querySelectorAll("[aria-label], img[alt]").forEach(element => {
    const attributes = {};

    ["aria-label", "alt"].forEach(attribute => {
      if (element.hasAttribute(attribute)) {
        attributes[attribute] = element.getAttribute(attribute);
      }
    });

    originalAttributes.set(element, attributes);
  });

  const normalizeText = text => text.trim().replace(/\s+/g, " ");

  // Atualiza os textos e atributos.
  const translatePage = language => {

    currentLanguage = language;

    const dictionary = translations[language] || {};

    // Textos do site.
    originalTextNodes.forEach((originalText, node) => {

      const key = normalizeText(originalText);

      if (language === "pt") {
        node.textContent = originalText;
        return;
      }

      const translated = dictionary[key];

      if (translated) {
        const leadingSpace = originalText.match(/^\s*/)?.[0] || "";
        const trailingSpace = originalText.match(/\s*$/)?.[0] || "";

        node.textContent = leadingSpace + translated + trailingSpace;
      } else {
        node.textContent = originalText;
      }

    });

    // Atributos de acessibilidade.
    originalAttributes.forEach((attributes, element) => {

      Object.entries(attributes).forEach(([attribute, originalValue]) => {

        if (language === "pt") {
          element.setAttribute(attribute, originalValue);
          return;
        }

        const translated =
          attributeTranslations[attribute]?.[originalValue];

        if (translated) {
          element.setAttribute(attribute, translated);
        }

      });

    });

    // Idioma do documento.
    document.documentElement.lang =
      language === "en" ? "en" : "pt-BR";

    // Título e descrição da página.
    document.title = language === "en"
      ? "Priscila Monteiro | Psychoanalysis and care"
      : "Priscila | Psicanálise e cuidado";

    const description = document.querySelector('meta[name="description"]');

    if (description) {
      description.content = language === "en"
        ? "Discover the work of Priscila Monteiro, psychoanalyst. A space for listening, support, and emotional care."
        : "Conheça o trabalho de Priscila, psicanalista. Um espaço de escuta, acolhimento e cuidado com a saúde emocional.";
    }

    // Botão de idioma.
    if (languageToggle) {

      languageToggle.textContent =
        language === "en" ? "PT" : "EN";

      languageToggle.setAttribute(
        "aria-label",
        language === "en"
          ? "Change language to Portuguese"
          : "Change language to English"
      );

    }

    // Menu responsivo.
    const menuToggle = document.querySelector(".menu-toggle");

    if (menuToggle) {

      const isOpen = menuToggle.getAttribute("aria-expanded") === "true";

      menuToggle.setAttribute(
        "aria-label",
        isOpen
          ? (language === "en" ? "Close menu" : "Fechar menu")
          : (language === "en" ? "Open menu" : "Abrir menu")
      );

    }

    // Botão do modo escuro.
    updateThemeButton();

    // Guarda o idioma escolhido.
    localStorage.setItem("site-language", language);

  };


  // =========================================
  // BOTÃO DE IDIOMA
  // =========================================

  if (languageToggle) {

    languageToggle.addEventListener("click", () => {

      const nextLanguage =
        currentLanguage === "pt" ? "en" : "pt";

      translatePage(nextLanguage);

    });

  }


  // =========================================
  // WHATSAPP
  // =========================================

  const updateWhatsAppLinks = () => {

    const message = SITE_CONFIG.whatsappMessage[currentLanguage];

    const whatsappUrl =
      `https://wa.me/${SITE_CONFIG.whatsapp}?text=${encodeURIComponent(message)}`;

    document.querySelectorAll("[data-whatsapp]").forEach(link => {
      link.href = whatsappUrl;
      link.target = "_blank";
      link.rel = "noopener noreferrer";
    });

  };


  // =========================================
  // GOOGLE REVIEWS
  // =========================================

  document.querySelectorAll("[data-google-reviews]").forEach(link => {

    if (SITE_CONFIG.googleReviewsUrl.trim()) {

      link.href = SITE_CONFIG.googleReviewsUrl;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

    } else {

      link.href = "#avaliacoes";

    }

  });

  // Incorporação opcional das avaliações.
  const reviewsEmbed = document.querySelector("#google-reviews-embed");

  if (reviewsEmbed && SITE_CONFIG.googleReviewsEmbedUrl.trim()) {

    const frame = document.createElement("iframe");

    frame.src = SITE_CONFIG.googleReviewsEmbedUrl;
    frame.title = "Avaliações do perfil profissional no Google";
    frame.loading = "lazy";
    frame.referrerPolicy = "no-referrer-when-downgrade";

    reviewsEmbed.replaceChildren(frame);
    reviewsEmbed.style.display = "block";

  }


  // =========================================
  // INSTAGRAM
  // =========================================

  document.querySelectorAll("[data-instagram]").forEach(link => {

    if (SITE_CONFIG.instagram.trim()) {

      link.href = SITE_CONFIG.instagram;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

    } else {

      link.href = "#";

      link.addEventListener("click", event => {
        event.preventDefault();

        alert(
          currentLanguage === "en"
            ? "Add the Instagram link in js/script.js."
            : "Adicione o link do Instagram no arquivo js/script.js."
        );

      });

    }

  });


  // =========================================
  // GOOGLE MAPS
  // =========================================

  const mapsUrl = SITE_CONFIG.address.trim()
    ? `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(SITE_CONFIG.address)}`
    : "";

  document.querySelectorAll("[data-maps]").forEach(link => {

    if (mapsUrl) {

      link.href = mapsUrl;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

    } else {

      link.href = "#localizacao";

    }

  });

  const addressText = document.querySelector("#address-text");

  if (addressText && SITE_CONFIG.address.trim()) {
    addressText.textContent = SITE_CONFIG.address;
  }

  // Mapa incorporado.
  const mapPlaceholder = document.querySelector(".map-placeholder");

  if (mapPlaceholder && SITE_CONFIG.address.trim()) {

    const mapFrame = document.createElement("iframe");

    mapFrame.src =
      `https://www.google.com/maps?q=${encodeURIComponent(SITE_CONFIG.address)}&output=embed`;

    mapFrame.title = currentLanguage === "en"
      ? `Location map: ${SITE_CONFIG.address}`
      : `Mapa de localização: ${SITE_CONFIG.address}`;

    mapFrame.loading = "lazy";
    mapFrame.referrerPolicy = "no-referrer-when-downgrade";
    mapFrame.style.width = "100%";
    mapFrame.style.height = "340px";
    mapFrame.style.border = "0";

    mapPlaceholder.replaceWith(mapFrame);

  }


  // =========================================
  // MENU RESPONSIVO
  // =========================================

  const menuToggle = document.querySelector(".menu-toggle");
  const mainNav = document.querySelector(".main-nav");

  if (menuToggle && mainNav) {

    menuToggle.addEventListener("click", () => {

      const isOpen = mainNav.classList.toggle("is-open");

      menuToggle.setAttribute("aria-expanded", String(isOpen));

      menuToggle.setAttribute(
        "aria-label",
        isOpen
          ? (currentLanguage === "en" ? "Close menu" : "Fechar menu")
          : (currentLanguage === "en" ? "Open menu" : "Abrir menu")
      );

    });

    mainNav.querySelectorAll("a").forEach(link => {

      link.addEventListener("click", () => {

        mainNav.classList.remove("is-open");

        menuToggle.setAttribute("aria-expanded", "false");

        menuToggle.setAttribute(
          "aria-label",
          currentLanguage === "en" ? "Open menu" : "Abrir menu"
        );

      });

    });

  }


  // =========================================
  // NAVEGAÇÃO POR SEÇÕES
  // =========================================

  const sectionSelect = document.querySelector("#section-select");

  if (sectionSelect) {

    sectionSelect.addEventListener("change", () => {

      const target = sectionSelect.value;

      if (target) {

        document.querySelector(target)?.scrollIntoView({
          behavior: "smooth",
          block: "start"
        });

        sectionSelect.value = "";

      }

    });

  }


  // =========================================
  // MODO ESCURO
  // =========================================

  const themeToggle = document.querySelector("#theme-toggle");

  const savedTheme = localStorage.getItem("site-theme") || "light";

  document.body.dataset.theme = savedTheme;

  function updateThemeButton() {

    if (!themeToggle) return;

    const darkMode = document.body.dataset.theme === "dark";

    themeToggle.innerHTML = darkMode
      ? '<span aria-hidden="true">☀</span>'
      : '<span aria-hidden="true">☾</span>';

    themeToggle.setAttribute(
      "aria-label",
      darkMode
        ? (currentLanguage === "en" ? "Enable light mode" : "Ativar modo claro")
        : (currentLanguage === "en" ? "Enable dark mode" : "Ativar modo escuro")
    );

  }

  updateThemeButton();

  if (themeToggle) {

    themeToggle.addEventListener("click", () => {

      const nextTheme =
        document.body.dataset.theme === "dark" ? "light" : "dark";

      document.body.dataset.theme = nextTheme;

      localStorage.setItem("site-theme", nextTheme);

      updateThemeButton();

    });

  }


  // =========================================
  // SLIDER DE APRESENTAÇÃO
  // =========================================

  const slider = document.querySelector("[data-slider]");

  if (slider) {

    const track = slider.querySelector("[data-track]");
    const cards = [...track.children];
    const dots = [...slider.querySelectorAll(".dot")];

    let current = 0;

    const showSlide = index => {

      current = (index + cards.length) % cards.length;

      track.style.transform = `translateX(-${current * 100}%)`;

      cards.forEach((card, i) => {
        card.setAttribute("aria-hidden", String(i !== current));
      });

      dots.forEach((dot, i) => {

        dot.classList.toggle("is-active", i === current);

        if (i === current) {
          dot.setAttribute("aria-current", "true");
        } else {
          dot.removeAttribute("aria-current");
        }

      });

    };

    slider.querySelector("[data-prev]").addEventListener(
      "click",
      () => showSlide(current - 1)
    );

    slider.querySelector("[data-next]").addEventListener(
      "click",
      () => showSlide(current + 1)
    );

    dots.forEach((dot, i) => {
      dot.addEventListener("click", () => showSlide(i));
    });

    showSlide(0);

  }


  // =========================================
  // ANIMAÇÃO AO ROLAR A PÁGINA
  // =========================================

  const revealItems = document.querySelectorAll(".reveal");

  if ("IntersectionObserver" in window) {

    const observer = new IntersectionObserver(entries => {

      entries.forEach(entry => {

        if (entry.isIntersecting) {

          entry.target.classList.add("is-visible");

          observer.unobserve(entry.target);

        }

      });

    }, { threshold: 0.12 });

    revealItems.forEach(item => observer.observe(item));

  } else {

    revealItems.forEach(item => item.classList.add("is-visible"));

  }


  // =========================================
  // CARREGAMENTO DA LOGO
  // =========================================

  document.querySelectorAll(".brand-logo").forEach(mark => {

    const logo = mark.querySelector(".logo-image");
    const fallback = mark.querySelector(".logo-fallback");

    if (!logo) return;

    logo.addEventListener("load", () => {

      logo.hidden = false;

      if (fallback) fallback.hidden = true;

    });

    logo.addEventListener("error", () => {

      logo.hidden = true;

      if (fallback) fallback.hidden = false;

    });

    if (logo.complete && logo.naturalWidth > 0) {

      logo.hidden = false;

      if (fallback) fallback.hidden = true;

    }

  });


  // =========================================
  // VOLTAR AO TOPO
  // =========================================

  document.querySelectorAll("[data-back-top]").forEach(link => {

    link.addEventListener("click", event => {

      event.preventDefault();

      window.scrollTo({
        top: 0,
        behavior: "smooth"
      });

      history.replaceState(null, "", "#topo");

    });

  });


  // =========================================
  // ANO AUTOMÁTICO
  // =========================================

  const year = document.querySelector("[data-year]");

  if (year) {
    year.textContent = new Date().getFullYear();
  }


  // =========================================
  // APLICA IDIOMA INICIAL
  // =========================================

  translatePage(currentLanguage);
  updateWhatsAppLinks();

});
